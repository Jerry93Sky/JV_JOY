import { chromium } from 'playwright'
import { createServer } from 'vite'
import { readFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const env = Object.fromEntries((await readFile(process.argv[2], 'utf8')).split(/\r?\n/).filter(s => s.includes('=')).map(s => { const i = s.indexOf('='); return [s.slice(0, i), s.slice(i + 1)] }))
const vite = await createServer({ configFile: 'vite.config.ts', root: '.', server: { host: '127.0.0.1', port: 0, proxy: { '/api': { target: 'http://127.0.0.1:3002' } } } })
await vite.listen()
const base = `http://127.0.0.1:${vite.httpServer.address().port}`
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = await context.newPage()
const unique = `R3.1-CODEX-${Date.now()}`, updated = `${unique}-EDIT`
try {
  await page.goto(`${base}/login`)
  await page.getByLabel('Логин', { exact: true }).fill('admin')
  await page.getByLabel('Пароль', { exact: true }).fill(env.JV_REVIEW_ADMIN_PASSWORD)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await page.waitForURL(u => !u.pathname.includes('login'))
  await page.goto(`${base}/vendors`)
  const add = page.getByRole('button', { name: 'Добавить поставщика' })
  await add.waitFor(); assert.equal(await add.isEnabled(), true, 'demo needs an existing vendor category')
  await add.click()
  let dialog = page.getByRole('dialog', { name: 'Новый поставщик' })
  await dialog.getByLabel('Название *').fill(unique)
  let response = page.waitForResponse(r => r.url().endsWith('/api/vendors') && r.request().method() === 'POST')
  await dialog.getByRole('button', { name: 'Сохранить' }).click()
  assert.equal((await response).ok(), true)
  await dialog.waitFor({ state: 'hidden' })
  let row = page.getByRole('row').filter({ hasText: unique })
  await row.waitFor()
  await row.locator('td').first().dblclick()
  dialog = page.getByRole('dialog', { name: 'Редактировать поставщика' })
  assert.equal(await dialog.getByLabel('Название *').inputValue(), unique)
  await dialog.getByLabel('Название *').fill(updated)
  response = page.waitForResponse(r => /\/api\/vendors\/[^/]+$/.test(r.url()) && r.request().method() === 'PATCH')
  await dialog.getByRole('button', { name: 'Сохранить' }).click()
  assert.equal((await response).ok(), true)
  await dialog.waitFor({ state: 'hidden' })
  await page.reload()
  row = page.getByRole('row').filter({ hasText: updated })
  await row.waitFor()
  await row.locator('td').first().dblclick()
  dialog = page.getByRole('dialog', { name: 'Редактировать поставщика' })
  assert.equal(await dialog.getByLabel('Название *').inputValue(), updated)
  await dialog.getByLabel('Название *').fill(`${updated}-CANCELLED`)
  await page.keyboard.press('Escape')
  await dialog.waitFor({ state: 'hidden' })
  await page.reload(); row = page.getByRole('row').filter({ hasText: updated }); await row.waitFor()
  page.once('dialog', prompt => prompt.dismiss())
  await row.getByRole('button', { name: 'Удалить поставщика' }).click()
  assert.equal(await row.isVisible(), true, 'cancelled deletion must preserve the test record')
  page.once('dialog', prompt => prompt.accept())
  response = page.waitForResponse(r => /\/api\/vendors\/[^/]+$/.test(r.url()) && r.request().method() === 'DELETE')
  await row.getByRole('button', { name: 'Удалить поставщика' }).click()
  assert.equal((await response).ok(), true)
  await row.waitFor({ state: 'hidden' })
  console.log('PASS real backend vendor create, double-click edit, reload, Escape/cancel, controlled test-record cleanup')
} finally { await context.close(); await browser.close(); await vite.close() }
